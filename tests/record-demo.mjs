import { chromium } from "playwright";
import { createServer } from "node:http";
import { readFileSync, mkdirSync } from "node:fs";
import { extname, join } from "node:path";
const types = { ".html": "text/html", ".js": "text/javascript", ".css": "text/css", ".woff2": "font/woff2" };
const srv = createServer((req, res) => { const p = join("dist/host", new URL(req.url, "http://x").pathname.replace(/\/$/, "/index.html")); let b; try { b = readFileSync(p); } catch { res.writeHead(404); res.end(); return; } res.writeHead(200, { "content-type": types[extname(p)] ?? "text/plain" }); res.end(b); }).listen(5175);
mkdirSync("dist/video", { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, recordVideo: { dir: "dist/video", size: { width: 1440, height: 900 } } });
const page = await ctx.newPage();
await page.goto(`http://localhost:5175/?server=http://localhost:8787&device=echo-show-8&scene=night`);
await page.waitForSelector("body[data-connected='1']");
const say = async (t, wait = 3500) => { await page.fill("#utter", t); await page.press("#utter", "Enter"); await page.waitForTimeout(wait); };
await page.waitForTimeout(800);
await say("I need to be at an 11 AM meeting in San Francisco tomorrow", 4200);
await say("Book the ride", 1800);
await page.click("#modal button[type=submit]"); await page.waitForTimeout(3500);
await page.selectOption("#scene", "airport"); await page.waitForTimeout(800);
await say("Watch my check-in time", 1500);
await page.waitForSelector("body[data-nudged='1']", { timeout: 30000 }); await page.waitForTimeout(4500);
await say("My flight got cancelled", 4200);
await say("Just book the 6 o'clock", 4800);
await say("Book it anyway", 1800);
await page.click("#modal input[type=checkbox]"); await page.waitForTimeout(900);
await page.click("#modal button[type=submit]"); await page.waitForTimeout(2600);
await page.click("#modal #no"); await page.waitForTimeout(2500);
await say("Flights that make it", 3500);
await say("Review UA 499 at 7:11 AM", 4200);
const v = page.video();
await ctx.close(); await browser.close(); srv.close();
console.log(await v.path());
